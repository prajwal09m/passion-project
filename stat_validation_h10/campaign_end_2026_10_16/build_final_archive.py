"""Campaign 4 final archive builder (Campaign 3 convention, 2026-10-09).

Copies the end-of-campaign state byte-for-byte into
autonomous_agent/MAIN AUDITS AND REFLECTIONS/CAMPAIGN_4_FINAL_ARCHIVE_2026-10-16/
and writes SHA256SUMS.txt.  No original is moved, modified, or deleted;
nothing here is generated by a new experiment.  README_FINAL.md is written
separately and included in the sums.
"""
from __future__ import annotations

import hashlib
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ARCHIVE = (ROOT / "autonomous_agent" / "MAIN AUDITS AND REFLECTIONS"
           / "CAMPAIGN_4_FINAL_ARCHIVE_2026-10-16")

COPIES: dict[str, str] = {
    "autonomous_agent/state/campaign_config.json": "campaign_config.json",
    "autonomous_agent/state/campaign_config.sha256": "campaign_config.sha256",
    "autonomous_agent/state/loop_state.json": "loop_state.json",
    "autonomous_agent/state/loop_events.jsonl": "loop_events.jsonl",
    "autonomous_agent/state/proposal_ledger.jsonl": "proposal_ledger.jsonl",
    "autonomous_agent/state/experiment_registry.json": "experiment_registry.json",
    "autonomous_agent/state/campaign_end_multiplicity.jsonl":
        "campaign_end_multiplicity.jsonl",
    "CHAMPION.json": "CHAMPION.final_v2.0.61.json",
    "autonomous_agent/candidates/exp-proposal-7628f97ad923/result.json":
        "final_experiment_result.json",
    "versions/V2.0.61/version.json": "v2.0.61_version.json",
    "versions/V2.0.61/evaluation.json": "v2.0.61_evaluation.json",
}


def main() -> int:
    ARCHIVE.mkdir(parents=True, exist_ok=True)
    sums: list[str] = []
    for src_rel, dst_name in COPIES.items():
        src = ROOT / src_rel
        if not src.is_file():
            print(f"FAIL: missing source {src_rel}", file=sys.stderr)
            return 1
        data = src.read_bytes()
        dst = ARCHIVE / dst_name
        if dst.exists() and dst.read_bytes() != data:
            print(f"FAIL: existing archive copy differs: {dst_name}",
                  file=sys.stderr)
            return 1
        if not dst.exists():
            shutil.copyfile(src, dst)
        if dst.read_bytes() != data:
            print(f"FAIL: copy mismatch {dst_name}", file=sys.stderr)
            return 1
        sums.append(f"{hashlib.sha256(data).hexdigest()}  {dst_name}")
        print(f"copied: {src_rel} -> {dst_name} ({len(data)} B)")
    readme = ARCHIVE / "README_FINAL.md"
    if readme.is_file():
        sums.append(f"{hashlib.sha256(readme.read_bytes()).hexdigest()}"
                    "  README_FINAL.md")
    sums_path = ARCHIVE / "SHA256SUMS.txt"
    sums_path.write_text("\n".join(sums) + "\n", encoding="utf-8",
                         newline="\n")
    print("wrote:", sums_path.relative_to(ROOT), f"({len(sums)} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
