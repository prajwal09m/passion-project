    axis = config.get("error_cluster_axis")
    axis_def = None
    for defn in predecl["cluster_definitions"]:
        if defn["experiment_axis"] == axis:
            axis_def = defn
            break
    if axis_def is None:
        raise RuntimeError(
            f"Config axis {axis!r} not found in predeclared axes; "
            f"predeclared axes: {[d['experiment_axis'] for d in predecl['cluster_definitions']]}")
    # Family-machinery identity: the collector is wired to one frozen family
    # through the same table the v1.1.0 collectors use; the identity dict the
    # caller built (config hash, arms, seeds, folds) rides in ctx.
    primitive_id = str(config.get("primitive_id") or "error_clustering_analysis")
    family = _FAMILY_COLLECTORS[primitive_id][0]
    identity = dict(ctx["identity"])

    # Validate rungs match the frozen ladder
    ladder = tv.ladder_for("error_clustering_analysis")
