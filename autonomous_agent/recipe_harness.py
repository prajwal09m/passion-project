    base = ctx["oof_frame"].reset_index(drop=True)
    score_a = base["score_a"].values
    score_b = base["score_b"].values
    labels = base["label"].values

    # Bootstrap parameters from predeclaration
    block_weeks = 4
    n_boot = int(config["n_boot"])
    seed = 42

    members = []
    for rung_def in axis_def["rungs"]:
        rung_key = rung_def["rung"]
        mask_expr = rung_def["mask"]

        # Evaluate the mask on the OOF frame
        # This is safe because masks are predeclared with intrinsic thresholds
