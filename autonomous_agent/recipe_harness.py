def evaluate_error_cluster_rungs(rung_measurements: list[dict], *,
                                 floors: Mapping[str, Any]) -> dict:
    """Error-cluster family evaluator: intersection-union three-valued logic.

    Both rungs must independently hold:
    - point >= 0.0 (B must not be worse than A)
    - ci_lower >= -0.01 (provisional margin from H-1 provenance)

    Floors (checked in collector):
    - min_rows = 50
    - min_events = 5

    Undersized or unavailable clusters are INCONCLUSIVE (never pass, never refute).
    Degenerate clusters are UNAVAILABLE with reason (counted toward m at p=1.0).

    Returns the IUT result dict with the family-level decision.
    """
    from autonomous_agent import three_valued as tv

    # Check if any rung is unavailable or inconclusive
    for m in rung_measurements:
        status = m.get("measurement_status", "ok")
        if status == "unavailable":
            return {
                "primitive_id": "error_clustering_analysis",
                "status": "UNAVAILABLE",
                "member_results": rung_measurements,
                "disclosure": f"Rung {m['rung']} is unavailable: {m.get('reason', 'unknown')}",
            }
        if status == "inconclusive":
            return {
                "primitive_id": "error_clustering_analysis",
                "status": "INCONCLUSIVE",
                "member_results": rung_measurements,
                "disclosure": f"Rung {m['rung']} is inconclusive: {m.get('reason', 'unknown')}",
            }

    # All rungs are OK; check intersection-union conditions
    # Both rungs must satisfy: point >= 0.0 AND ci_lower >= -0.01
    margin = -0.01  # Provisional margin from H-1 provenance
    for m in rung_measurements:
        point = m["point"]
        ci_lower = m["ci_lower"]
        if point < 0.0 or ci_lower < margin:
            return {
                "primitive_id": "error_clustering_analysis",
                "status": "FAIL",
                "member_results": rung_measurements,
                "disclosure": (f"Rung {m['rung']} fails intersection-union: "
                              f"point={point:.4f} < 0.0 or ci_lower={ci_lower:.4f} < {margin}"),
            }

    # All rungs pass
    return {
        "primitive_id": "error_clustering_analysis",
        "status": "PASS",
        "member_results": rung_measurements,
        "disclosure": "Both rungs satisfy intersection-union: point >= 0.0 and ci_lower >= -0.01",
    }


