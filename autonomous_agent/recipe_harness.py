def _oof_scores(study, frame, config, *, exit_shift_sessions=0,
                session_calendar=None):
    """Purged walk-forward OOF scores for arm_a / arm_b on ``frame``.

    Mirrors the frozen study fold contract (train rows require
    ``exit_date < fold start``); ``exit_shift_sessions`` > 0 widens the
    training maturity purge by N market sessions on the provided session
    calendar (the purge rungs).  Validation rows are identical to the
    frozen rule in both cases — only the training exclusion changes.
    """
    import numpy as np
    import pandas as pd
    labels_all = frame["label"].astype(int)
    folds = study.make_folds(frame, years=tuple(config["folds"]))
    cutoffs: dict[str, Any] = {}
    if exit_shift_sessions:
        if session_calendar is None or len(session_calendar) == 0:
            raise RuntimeError("purge rungs require the frozen session calendar")
        calendar = pd.DatetimeIndex(session_calendar)
        for fold in folds:
            start = pd.Timestamp(fold["start"])
            earlier = calendar[calendar < start]
            if len(earlier) < int(exit_shift_sessions):
                raise RuntimeError(
                    f"purge rung +{exit_shift_sessions} leaves no training "
                    f"history before fold {fold['name']}")
            cutoffs[fold["name"]] = earlier[-int(exit_shift_sessions)]
    features_a = list(study.FEATURE_ARMS[config["arm_a"]])
    features_b = list(study.FEATURE_ARMS[config["arm_b"]])
    score_a = np.full(len(frame), np.nan)
    score_b = np.full(len(frame), np.nan)
    oof = np.zeros(len(frame), dtype=bool)
    exits = pd.to_datetime(frame["exit_date"])
    for fold in folds:
        train_idx = np.flatnonzero(fold["train_mask"])
        if exit_shift_sessions:
            train_idx = train_idx[
                (exits < cutoffs[fold["name"]]).to_numpy()[train_idx]]
        valid_idx = np.flatnonzero(fold["valid_mask"])
        train_rows = frame.iloc[train_idx]
        if train_rows.empty or valid_idx.size == 0:
            raise RuntimeError(f"Fold {fold['name']} lacks train or validation rows.")
        train_labels = labels_all.iloc[train_idx].to_numpy()
        pipeline_a = study.fit_pipeline(config["estimator_a"], features_a,
                                        train_rows, train_labels)
        pipeline_b = study.fit_pipeline(config["estimator_b"], features_b,
                                        train_rows, train_labels)
        score_a[valid_idx] = study.predict_pipeline(pipeline_a, frame.iloc[valid_idx])
        score_b[valid_idx] = study.predict_pipeline(pipeline_b, frame.iloc[valid_idx])
        oof[valid_idx] = True
    return score_a, score_b, oof


