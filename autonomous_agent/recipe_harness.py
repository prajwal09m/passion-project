def _rebuild_horizon_frame(base, opens, sessions):
    """H-2/H3 label rebuild: h-session hold, same +2% inclusive threshold.

    Rebuilt from the frozen OHLCV opens (derived data only), exit dates
    recomputed per rung, unmatured rows removed.  The 1-session rung is
    anchored to the frozen table: rebuilt returns/labels/exit dates must
    reproduce the recorded columns exactly or the run fails.
    """
    import numpy as np
    import pandas as pd
    entry_dates = pd.to_datetime(base["entry_date"])
    table_ret = pd.to_numeric(base["hold1_ret"], errors="coerce").to_numpy()
    table_exit = pd.to_datetime(base["exit_date"]).to_numpy()
    table_label = base["label"].astype(int).to_numpy()
    rows: list[dict[str, Any]] = []
    rebuilt_ret: list[float] = []
    rebuilt_exit: list[Any] = []
    rebuilt_label: list[int] = []
    for position, (_, row) in enumerate(base.iterrows()):
        ticker = str(row["ticker"])
        if ticker not in opens:
            raise RuntimeError(f"no frozen OHLCV opens for ticker {ticker!r}")
        series = opens[ticker]
        entry = pd.Timestamp(entry_dates.iloc[position])
        location = int(series.index.searchsorted(entry))
        if location >= len(series) or series.index[location] != entry:
            raise RuntimeError(
                f"{ticker}: entry_date {entry.date()} missing from the frozen cache")
        if location + int(sessions) >= len(series):
            continue   # unmatured at this horizon: removed for this rung
        exit_date = series.index[location + int(sessions)]
        open_entry = float(series.iloc[location])
        open_exit = float(series.iloc[location + int(sessions)])
        hold_return = open_exit / open_entry - 1.0
        record = dict(row)
        record["exit_date"] = str(pd.Timestamp(exit_date).date())
        record["label"] = 1 if hold_return >= 0.02 else 0
        rows.append(record)
        rebuilt_ret.append(hold_return)
        rebuilt_exit.append(np.datetime64(pd.Timestamp(exit_date)))
        rebuilt_label.append(int(record["label"]))
    frame_h = pd.DataFrame(rows)
    if int(sessions) == 1:
        if len(frame_h) != len(base):
            raise RuntimeError(
                "1-session rebuild dropped matured rows; the anchor to the "
                "frozen table failed")
        if max(abs(a - b) for a, b in zip(rebuilt_ret, table_ret)) > 1e-9:
            raise RuntimeError(
                "1-session rebuild does not reproduce hold1_ret; the anchor "
                "to the frozen table failed")
        if [int(x) for x in rebuilt_label] != [int(x) for x in table_label] or \
                [str(x)[:10] for x in rebuilt_exit] != [str(x)[:10] for x in table_exit]:
            raise RuntimeError(
                "1-session rebuild does not reproduce label/exit_date; the "
                "anchor to the frozen table failed")
    return frame_h


