def _evaluate_cluster_mask(frame: pd.DataFrame, mask_expr: str) -> np.ndarray:
    """Evaluate a predeclared cluster mask expression on a dataframe.

    This is a restricted evaluator that only allows:
    - Column names from the frame
    - Comparison operators: >=, <=, ==, !=, <, >
    - Logical operators: and, or, not
    - Numeric constants
    - Parentheses

    This is safe because all expressions are owner-predeclared in the
    frozen record and use only intrinsic thresholds.
    """
    import numpy as np

    # Parse the expression into column name, operator, and value
    # Supported patterns: "column >= value", "column == value", etc.
    expr = mask_expr.strip()

    # Simple parser for the allowed patterns
    operators = [">=", "<=", "==", "!=", "<", ">"]
    op = None
    for o in operators:
        if o in expr:
            op = o
            break

    if op is None:
        raise ValueError(f"Mask expression must contain a comparison operator: {expr}")

    parts = expr.split(op)
    if len(parts) != 2:
        raise ValueError(f"Mask expression must have exactly one operator: {expr}")

    col_name = parts[0].strip()
    value_str = parts[1].strip()

    # Get the column
    if col_name not in frame.columns:
        raise ValueError(f"Column {col_name!r} not in frame columns")

    col = frame[col_name].values

    # Parse the value (could be int, float, bool)
    try:
        if value_str in ("True", "False"):
            value = value_str == "True"
        else:
            value = float(value_str)
    except ValueError:
        raise ValueError(f"Cannot parse value {value_str!r} as numeric or boolean")

    # Apply the comparison
    if op == ">=":
        return col >= value
    elif op == "<=":
        return col <= value
    elif op == "==":
        return col == value
    elif op == "!=":
        return col != value
    elif op == "<":
        return col < value
    elif op == ">":
        return col > value
    else:
        raise ValueError(f"Unsupported operator {op}")


def _bootstrap_cluster_delta(score_a: np.ndarray, score_b: np.ndarray,
                            labels: np.ndarray, block_weeks: int,
                            n_boot: int, seed: int) -> tuple[float, float]:
    """Moving-block bootstrap CI for AUC delta.

    Follows the frozen campaign configuration: block_weeks=4, n_boot from config,
    seed 42. Returns (ci_lower, ci_upper).
    """
    import numpy as np
    from sklearn.metrics import roc_auc_score

    n = len(labels)
    if n == 0:
        return 0.0, 0.0

    rng = np.random.default_rng(seed)

    # Compute observed delta
    delta_obs = roc_auc_score(labels, score_b) - roc_auc_score(labels, score_a)

    # Bootstrap resamples
    boot_deltas = np.empty(n_boot)
    block_size = block_weeks * 5  # Assume ~5 trading days per week

    for i in range(n_boot):
        # Moving-block resampling
        indices = []
        while len(indices) < n:
            start = rng.integers(0, n - block_size + 1)
            block = list(range(start, min(start + block_size, n)))
            indices.extend(block)
        indices = np.array(indices[:n])

        # Compute bootstrap delta
        delta_boot = (roc_auc_score(labels[indices], score_b[indices]) -
                      roc_auc_score(labels[indices], score_a[indices]))
        boot_deltas[i] = delta_boot

    # Percentile CI
    ci_lower = np.percentile(boot_deltas, 2.5)
    ci_upper = np.percentile(boot_deltas, 97.5)

    return float(ci_lower), float(ci_upper)


_FAMILY_COLLECTORS = {
    "regime_split_analysis": ("regime", _collect_regime),
    "target_horizon_robustness": ("horizon", _collect_horizon),
    "purge_sensitivity_probe": ("purge", _collect_purge),
    "complexity_reduction_check": ("complexity", _collect_complexity),
    "error_clustering_analysis": ("error_analysis", _collect_error_cluster),
}


def _evaluate_members(primitive_id: str, family: str, members) -> dict[str, Any]:
    """Run the frozen IUT evaluator over the collected members.

    Unavailable members enter with zero events, which the frozen floors
    resolve to INCONCLUSIVE before any point/CI comparison — they can
    never pass and never refute.
    """
    floors = _frozen_floors()

    def entry(m, *, cell=None, rung=None):
        row: dict[str, Any] = {
            "point": float(m.get("point") if m.get("point") is not None else 0.0),
            "ci_lower": float(m.get("ci_lower") if m.get("ci_lower") is not None else 0.0),
            "n_rows": m["n_rows"],
            "n_events": m["n_events"] if m["measurement_status"] == "ok" else 0,
        }
        if cell is not None:
            row["cell"] = cell
        if rung is not None:
            row["rung"] = rung
        return row

    if family == "regime":
        return evaluate_regime_cells(
            [entry(m, cell=m["member_key"]) for m in members], floors=floors)
    if family == "horizon":
        # The frozen evaluator refuses a rung that does not declare its
        # label rebuild / purge re-verification; the declaration travels
        # with the member's persisted flags.
        rows = []
        for m in members:
            flags = m.get("flags") or {}
            rows.append(dict(
                entry(m, rung=int(m["member_key"])),
                labels_rebuilt=bool(flags.get("labels_rebuilt")),
                maturity_purge_reverified=bool(
                    flags.get("maturity_purge_reverified"))))
        return evaluate_horizon_rungs(rows, floors=floors)
    if family == "purge":
        return evaluate_purge_rungs(
            [entry(m, rung=int(m["member_key"])) for m in members],
            floors=floors)
    if family == "complexity":
        primary = members[0]
        return evaluate_complexity_reduction(
            entry(primary, rung=primary["member_key"]), floors=floors)
    if family == "error_analysis":
        # Error-cluster family: intersection-union three-valued logic
        # Both rungs must independently hold: point >= 0.0 AND ci_lower >= -0.01
        # Floors: min_rows=50, min_events=5 (checked in collector)
        # Undersized/unavailable clusters are INCONCLUSIVE
        rows = []
        for m in members:
            rows.append(dict(
                entry(m, rung=m["member_key"]),
                measurement_status=m.get("measurement_status", "ok"),
                reason=m.get("reason")))
        return evaluate_error_cluster_rungs(rows, floors=floors)
    raise RuntimeError(f"no frozen evaluator for family {family!r}")


def _collect_family_measurements(config: Mapping[str, Any], root: Path,
                                 study, ctx: Mapping[str, Any]) -> dict[str, Any]:
    """Collect, evaluate, and assemble the persisted family-measurement block."""
    import hashlib as _hashlib
    from autonomous_agent import three_valued as tv
    primitive_id = str(config.get("primitive_id") or "")
    if primitive_id not in _FAMILY_COLLECTORS:
        return {
            "schema": FAMILY_MEASUREMENTS_SCHEMA,
            "applicable": False,
            "primitive_id": primitive_id,
            "reason": ("no Holm family is declared for this primitive; no "
                       "family-dependent evaluation is claimed"),
        }
    n_boot = int(config["n_boot"])
    if n_boot < int(tv.MIN_BOOT_FOR_INFERENCE):
        # H-10b floor, re-checked on the execution side (fail-closed).
        raise RuntimeError(
            f"family-feeding experiments require n_boot >= "
            f"{tv.MIN_BOOT_FOR_INFERENCE}; got {n_boot}")
    family, collector = _FAMILY_COLLECTORS[primitive_id]
    identity = {
        "hypothesis_id": str(config.get("hypothesis_id") or ""),
        "recipe_id": str(config.get("recipe_id") or ""),
        "arm_a": config["arm_a"], "arm_b": config["arm_b"],
        "estimator_a": config["estimator_a"],
        "estimator_b": config["estimator_b"],
        "seeds": [int(seed) for seed in config["seeds"]],
        "n_boot": n_boot,
        "folds": [int(year) for year in config["folds"]],
        "config_sha256": _hashlib.sha256(
            json.dumps(config, sort_keys=True).encode("utf-8")).hexdigest(),
    }
    local_ctx = {**dict(ctx), "identity": identity}
    members = collector(config, root, study, local_ctx)
    ladder = tv.ladder_for(primitive_id)
    expected = [str(rung) for rung in ladder["rungs"]]
    seen = [str(m["member_key"]) for m in members]
    if len(members) != len(expected) or sorted(seen) != sorted(expected):
        raise RuntimeError(
            f"family member set incomplete: expected {expected}, produced "
            f"{seen}; a v1.1.0 run may never persist a partial member set")
    iut = _evaluate_members(primitive_id, family, members)
    hv = config.get("harness_version", HARNESS_VERSION_1_1_0)
    block = {
        "schema": FAMILY_MEASUREMENTS_SCHEMA,
        "applicable": True,
        "harness_version": hv,
        "primitive_id": primitive_id,
        "family": family,
        "identity": identity,
        "week_index": {
            "W": int(len(ctx["week_index"])),
            "convention": "W-SUN periods of the pooled out-of-fold frame",
            "weeks": [str(week) for week in ctx["week_index"]],
        },
        "member_bound": int(tv.FAMILY_MEMBER_BOUNDS[family]),
        "members": members,
        "iut_result": iut,
        "member_set_complete": True,
        "p_value_method_at_campaign_end": CAMPAIGN_END_P_VALUE_METHOD,
        "firewall": {
            "refutation_signal": tv.REFUTATION_SIGNAL_VALUE,
            "formal_refutation": False,
            "note": ("provisional signals only; the bare formal label is "
                     "assigned exclusively by the campaign-end multiplicity "
                     "record"),
        },
    }
    # The provisional-to-formal firewall is enforced where this block is
    # consumed and where it is adjudicated — both of which may import the
    # multiplicity machinery; the execution path may not (T12 / freeze
    # import boundary).  ``continuous_loop._adjudicate`` already runs the
    # campaign-side firewall over adjudication results (this block rides
    # inside them), and the stat-validation-side consumption module
    # (``stat_validation_h10/family_records.py``) re-checks it before any
    # campaign-end use.
    return block
