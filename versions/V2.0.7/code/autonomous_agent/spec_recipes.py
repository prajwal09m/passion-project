# Deterministic spec provider
# ---------------------------------------------------------------------------

class RecipeSpecProvider:
    """Deterministic, evidence-grounded, closed-recipe ExperimentSpec provider.

    Callable as ``provider(hypothesis, report) -> ExperimentSpec`` to match
    ``build_experiment_runner``'s ``spec_provider`` contract. Any refusal raises
    :class:`SpecGenerationRefused`, which the runner records as a normal
    rejection -- the loop keeps running, nothing is weakened.
    """

    def __init__(self, root: Path, *, allow_autonomous_specs: bool | None = None,
                 library: Sequence[Recipe] | None = None,
                 registry: Any = None, clock: Callable[[], str] = utc_now):
        self.root = Path(root)
        self.clock = clock
        self.library = tuple(library) if library is not None else RECIPE_LIBRARY
        if allow_autonomous_specs is None:
            allow_autonomous_specs = autonomous_specs_enabled(self.root)
        self.allow_autonomous_specs = bool(allow_autonomous_specs)
        self.registry = registry if registry is not None else hardening.SpecRegistry(
            self.root / "autonomous_agent" / "state")

    # -- refusal helper -----------------------------------------------------
    @staticmethod
    def _refuse(reason_code: str, reason: str) -> None:
        raise SpecGenerationRefused(reason_code, reason)

    # -- recipe selection ---------------------------------------------------
    def _select_recipe(self, hypothesis: Hypothesis) -> Recipe | None:
        valid, _ = validated_library(self.library)
        for recipe in valid:
            if recipe.direction == hypothesis.direction:
                return recipe
        return None

    def _build_spec(self, recipe: Recipe, hypothesis: Hypothesis, params: dict[str, Any],
                    evidence: Mapping[str, Any], baseline_id: str | None) -> ExperimentSpec:
        config = self._render_config(recipe, hypothesis, params, evidence, baseline_id)
        attempt_index = len(attempts_for_recipe(self.root, recipe.recipe_id))
        experiment_id = f"exp-{recipe.recipe_id.replace('_', '-')}-a{attempt_index:02d}"
        changes = [
            {"path": f"{EXPERIMENT_DIR}/__init__.py", "content": INIT_CONTENT},
            {"path": f"{EXPERIMENT_DIR}/run_experiment.py", "content": EXPERIMENT_ENTRYPOINT},
            {"path": f"{EXPERIMENT_DIR}/experiment_config.json", "content": config},
        ]
        provenance = {
            "generator_type": GENERATOR_TYPE,
            "generator_version": GENERATOR_VERSION,
            "provider": PROVIDER_NAME,
            "recipe_id": recipe.recipe_id,
            "recipe_version": recipe.version,
            "hypothesis_id": _hypothesis_id(hypothesis),
            "grounding_evidence": dict(evidence),
            "selected_parameters": dict(params),
            "generated_at": self.clock(),
            "llm_involved": False,
        }
        spec = ExperimentSpec(
            experiment_id=experiment_id,
            parent_version=self.parent_version_for(hypothesis),
            hypothesis=f"[{hypothesis.direction}] {hypothesis.question}",
            proposed_change={
                "summary": (f"Recipe {recipe.recipe_id} v{recipe.version}: {recipe.purpose}"),
                "files": changes,
            },
            files_allowed_to_change=tuple(recipe.target_files),
            evaluation_protocol={"acceptance_criteria": dict(recipe.evaluation_criteria)},
            random_seed=42,
            resource_limits={},
            timeout=float(recipe.timeout),
            allow_repeat=False,
            baseline_id=baseline_id,
            provenance=provenance,
        )
        return spec

    def parent_version_for(self, hypothesis: Hypothesis) -> str:
        """Establish the current parent version from CHAMPION.json, or refuse.

        Fail closed: if the champion manifest is missing, unreadable, malformed,
        or lacks a version on the champion version ladder, generation is refused
        with ``INVALID_PARENT``. A parent version is never guessed or defaulted.
        """
        path = self.root / "CHAMPION.json"
        champion = read_json(path, None)
        if not isinstance(champion, dict):
            self._refuse(
                "INVALID_PARENT",
                f"Cannot establish the parent version: {path.name} is missing, unreadable, "
                "or malformed; autonomous spec generation is refused rather than guessing "
                "a parent version.")
        version = champion.get("version")
        if not isinstance(version, str) or VersionManager.VERSION_PATTERN.fullmatch(version) is None:
            self._refuse(
                "INVALID_PARENT",
                f"Cannot establish the parent version: {path.name} has no valid version "
                "field; autonomous spec generation is refused rather than guessing a "
                "parent version.")
        return version

    def _render_config(self, recipe: Recipe, hypothesis: Hypothesis, params: Mapping[str, Any],
                       evidence: Mapping[str, Any], baseline_id: str | None) -> str:
        # Parameter unpacking is structural: only reviewed keys, only reviewed
        # shapes. A malformed grid entry refuses the whole proposal.
        arm_a, arm_b = "B", "C"
        estimator_a, estimator_b = "LogisticRegression", "LightGBM"
        if "arm_pair" in params:
            value = params["arm_pair"]
            if not isinstance(value, str) or "->" not in value:
                self._refuse("INVALID_PARAMETERS", f"arm_pair {value!r} is not 'X->Y'.")
            arm_a, arm_b = value.split("->", 1)
            estimator_a = estimator_b = str(params.get("estimator", "LightGBM"))
        elif "arm" in params:
            arm_a = arm_b = str(params["arm"])
            estimator_a, estimator_b = "LogisticRegression", "LightGBM"
        else:
            self._refuse("INVALID_PARAMETERS", "Recipe grid declares no arm parameter.")
        n_boot = params.get("n_boot", 500)
        bins = params.get("calibration_bins", 10)
        if isinstance(n_boot, bool) or not isinstance(n_boot, int) or not 100 <= n_boot <= 2000:
            self._refuse("INVALID_PARAMETERS", f"n_boot {n_boot!r} outside [100, 2000].")
        if isinstance(bins, bool) or not isinstance(bins, int) or not 3 <= bins <= 20:
            self._refuse("INVALID_PARAMETERS", f"calibration_bins {bins!r} outside [3, 20].")
        config = {
            "schema_version": 1,
            "generator": GENERATOR_TYPE,
            "recipe_id": recipe.recipe_id,
            "recipe_version": recipe.version,
            "hypothesis_id": _hypothesis_id(hypothesis),
            "hypothesis_text": hypothesis.question,
            "baseline_id": baseline_id,
            "arm_a": arm_a,
            "arm_b": arm_b,
            "estimator_a": estimator_a,
            "estimator_b": estimator_b,
            "seeds": [42, 43, 44],
            "n_boot": int(n_boot),
            "calibration_bins": int(bins),
            "folds": [2023, 2024, 2025],
            "evaluation_criteria": dict(recipe.evaluation_criteria),
        }
        try:
            from autonomous_agent.recipe_harness import validate_experiment_config
        except ImportError:
            from recipe_harness import validate_experiment_config  # type: ignore
        problems = validate_experiment_config(config)
        if problems:
            self._refuse("INVALID_PARAMETERS",
                         "Rendered config failed the harness contract: " + "; ".join(problems))
        return json.dumps(config, indent=2, sort_keys=True) + "\n"

    # -- main entry points --------------------------------------------------
    def propose(self, hypothesis: Hypothesis, report: PrerequisiteReport | None = None,
                *, dry_run: bool = False) -> tuple[ExperimentSpec | None, dict[str, Any]]:
        """Return (spec | None, review record). Refusals raise, except in dry_run
        mode where they are returned in the review record for the report."""
        record: dict[str, Any] = {
            "hypothesis_id": _hypothesis_id(hypothesis),
            "direction": hypothesis.direction,
            "generated_at": self.clock(),
        }
        try:
            spec, recipe = self._propose(hypothesis, dry_run=dry_run)
        except SpecGenerationRefused as refusal:
            record.update({"status": "REFUSED", "reason_code": refusal.reason_code,
                           "reason": refusal.reason})
            if dry_run:
                return None, record
            raise
        record.update({"status": "GENERATED",
                       "recipe_id": recipe.recipe_id,
                       "recipe_version": recipe.version,
                       "experiment_id": spec.experiment_id,
                       "spec_sha256": hardening.spec_fingerprint(spec.to_dict()),
                       "provenance": dict(spec.provenance)})
        return spec, record

    def _propose(self, hypothesis: Hypothesis, *, dry_run: bool) -> tuple[ExperimentSpec, Recipe]:
        if not self.allow_autonomous_specs:
            self._refuse("DISABLED",
                         "allow_autonomous_specs is false; autonomous spec generation is "
                         "disabled and candidate specs are prohibited.")
        recipe = self._select_recipe(hypothesis)
        if recipe is None:
            self._refuse("UNSUPPORTED",
                         f"No reviewed recipe covers hypothesis direction {hypothesis.direction!r}; "
                         "the closed library will not improvise a design.")
        recipe_problems = validate_recipe(recipe)
        if recipe_problems:
            self._refuse("MALFORMED_RECIPE",
                         f"Recipe {recipe.recipe_id!r} is unusable: " + "; ".join(recipe_problems))
        evidence, missing = gather_evidence(self.root, recipe)
        if missing:
            self._refuse("MISSING_EVIDENCE",
                         f"Recipe {recipe.recipe_id!r} is insufficiently grounded: "
                         + "; ".join(missing))
        attempts = attempts_for_recipe(self.root, recipe.recipe_id)
        if len(attempts) >= recipe.max_attempts:
            self._refuse("BUDGET_EXHAUSTED",
                         f"Recipe {recipe.recipe_id!r} attempt budget exhausted "
                         f"({len(attempts)}/{recipe.max_attempts}); further proposals are refused.")
        grid = recipe.grid()
        if not grid:
            self._refuse("MALFORMED_RECIPE", "Recipe parameter grid is empty.")
        params = grid[len(attempts) % len(grid)]
        baseline_id = (evidence.get("established_baseline") or {}).get("baseline_id")
        spec = self._build_spec(recipe, hypothesis, params, evidence, baseline_id)
        spec.validate()  # mechanical contract check before anything else sees it
        fingerprint = hardening.spec_fingerprint(spec.to_dict())
        # Duplicate refusal in two independent layers: this provider's own
        # attempt ledger (crash-safe, at-most-once) and the adapter's spec
        # registry (which also covers specs attempted through other paths).
        if any(row.get("spec_sha256") == fingerprint for row in attempts):
            self._refuse("DUPLICATE",
                         f"Generated spec {fingerprint[:16]} duplicates an already-recorded "
                         f"attempt of recipe {recipe.recipe_id!r}; repeats require an explicit "
                         "human-reviewed allow_repeat spec, which this provider never sets.")
        allowed, registry_reason = self.registry.check(spec.to_dict())
        if not allowed:
            self._refuse("DUPLICATE", registry_reason)
        if not dry_run:
            # Record the attempt before returning so a crash cannot double-run.
            _record_attempt(self.root, {
                "recipe_id": recipe.recipe_id,
                "recipe_version": recipe.version,
                "hypothesis_id": _hypothesis_id(hypothesis),
                "experiment_id": spec.experiment_id,
                "selected_parameters": dict(params),
                "spec_sha256": fingerprint,
                "at": self.clock(),
            })
        return spec, recipe

    def __call__(self, hypothesis: Hypothesis, report: PrerequisiteReport | None = None) -> ExperimentSpec:
        spec, _ = self.propose(hypothesis, report)
        assert spec is not None
        return spec


def build_default_provider(root: Path) -> RecipeSpecProvider | None:
    """Return the provider only when autonomous generation is explicitly enabled.

    When disabled (the default) this returns ``None`` and the runner keeps its
    existing, safe behavior: candidate specs are refused with the documented
    'no reviewed ExperimentSpec provider' rejection.
    """
    if not autonomous_specs_enabled(root):
        return None
    return RecipeSpecProvider(root, allow_autonomous_specs=True)


# ---------------------------------------------------------------------------
# Dry-run review mode (no experiments, no champion changes, no writes)
# ---------------------------------------------------------------------------

def dry_run(root: Path, hypotheses: Iterable[Hypothesis] | None = None) -> dict[str, Any]:
    """Generate and validate proposals for review only.

    Read-only with respect to research state: attempt rows are NOT recorded,
    the registry is NOT written, no experiment executes, and the champion is
    untouched. Safe to run while the supervisor is live.
    """
    from autonomous_agent.core import ResearchPlanner  # local import avoids cycles
    root = Path(root)
    provider = RecipeSpecProvider(root, allow_autonomous_specs=True)
    directions = list(hypotheses) if hypotheses is not None else [
        Hypothesis(h.direction, h.question, h.rationale, h.experiment, h.required_inputs, h.priority)
        for h in ResearchPlanner.BASE_DIRECTIONS]
    valid, malformed = validated_library()
    proposals: list[dict[str, Any]] = []
    for hypothesis in directions:
        _, record = provider.propose(hypothesis, dry_run=True)
        proposals.append(record)
    selected = [row for row in proposals if row.get("status") == "GENERATED"]
    refused = [row for row in proposals if row.get("status") == "REFUSED"]
    return {
        "mode": "dry_run",
        "generator_type": GENERATOR_TYPE,
        "llm_involved": False,
        "allow_autonomous_specs_in_config": autonomous_specs_enabled(root),
        "recipes": [
            {"recipe_id": recipe.recipe_id, "version": recipe.version,
             "direction": recipe.direction, "purpose": recipe.purpose,
             "target_files": list(recipe.target_files),
             "parameter_grid": {key: list(values) for key, values in recipe.parameter_grid.items()},
             "required_evidence": list(recipe.required_evidence),
             "evaluation_criteria": dict(recipe.evaluation_criteria),
             "rejection_conditions": list(recipe.rejection_conditions),
             "max_attempts": recipe.max_attempts}
            for recipe in valid
        ],
        "malformed_recipes": malformed,
        "proposals": proposals,
        "summary": {
            "generated": len(selected),
            "refused": len(refused),
            "refusal_reasons": {row.get("reason_code"): row.get("reason") for row in refused},
        },
        "executed_experiments": 0,
        "champion_changed": False,
    }


def main(argv: Sequence[str] | None = None) -> int:
    import argparse
    parser = argparse.ArgumentParser(
        description="Deterministic recipe spec generation (no LLM involved).")
    subparsers = parser.add_subparsers(dest="command", required=True)
    run_parser = subparsers.add_parser(
        "dry-run", help="Generate and validate proposals for review; execute nothing.")
    run_parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    subparsers.add_parser("show-recipes", help="Print the closed recipe library.")
    args = parser.parse_args(list(argv) if argv is not None else None)
    if args.command == "show-recipes":
        valid, malformed = validated_library()
        print(json.dumps({
            "recipes": [{"recipe_id": r.recipe_id, "version": r.version,
                         "direction": r.direction, "purpose": r.purpose,
                         "target_files": list(r.target_files),
                         "parameter_grid": {k: list(v) for k, v in r.parameter_grid.items()},
                         "required_evidence": list(r.required_evidence),
                         "evaluation_criteria": dict(r.evaluation_criteria),
                         "rejection_conditions": list(r.rejection_conditions),
                         "max_attempts": r.max_attempts} for r in valid],
            "malformed": malformed,
        }, indent=2, sort_keys=True))
        return 0
    report = dry_run(args.root)
    print(json.dumps(report, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
