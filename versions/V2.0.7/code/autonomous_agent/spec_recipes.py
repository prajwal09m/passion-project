@dataclass(frozen=True)
class Recipe:
    """One reviewed experiment design.

    ``parameter_grid`` maps a parameter name to its full, reviewed set of
    permitted values; only combinations from the cartesian product of these
    sets can ever be selected. ``required_evidence`` names the evidence kinds
    that must be present in the research memory / experiment records before
    this recipe may propose anything. ``rejection_conditions`` documents, in
    words, when the recipe must be refused (the provider enforces the same
    conditions structurally).
    """

    recipe_id: str
    version: str
    direction: str
    purpose: str
    target_files: tuple[str, ...]
    parameter_grid: Mapping[str, tuple[Any, ...]]
    required_evidence: tuple[str, ...]
    evaluation_criteria: Mapping[str, Any]
    rejection_conditions: tuple[str, ...]
    max_attempts: int = 3
    timeout: float = 1800.0

    def grid(self) -> list[dict[str, Any]]:
        keys = sorted(self.parameter_grid)
        if not keys:
            return []
        combos = itertools.product(*(self.parameter_grid[key] for key in keys))
        return [dict(zip(keys, values)) for values in combos]


def _arm_pair(*pairs: tuple[str, str]) -> tuple[Any, ...]:
    return tuple(f"{a}->{b}" for a, b in pairs)


