class SpecGenerationRefused(Exception):
    """A proposal was refused. Never suppress this: it is a safety decision."""

    def __init__(self, reason_code: str, reason: str):
        super().__init__(f"[{reason_code}] {reason}")
        self.reason_code = reason_code
        self.reason = reason


