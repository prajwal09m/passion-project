def load_autonomy_config(root: Path) -> dict[str, Any]:
    """Load the autonomy config. Missing or malformed config means *disabled*."""
    path = Path(root) / "autonomous_agent" / CONFIG_FILE
    data = read_json(path, {})
    return data if isinstance(data, dict) else {}


