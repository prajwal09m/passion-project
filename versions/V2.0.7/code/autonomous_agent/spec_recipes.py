def _hypothesis_id(hypothesis: Hypothesis) -> str:
    raw = f"{hypothesis.direction}\n{hypothesis.question}".encode("utf-8")
    return f"hyp-{hashlib.sha256(raw).hexdigest()[:12]}"


def gather_evidence(root: Path, recipe: Recipe) -> tuple[dict[str, Any], list[str]]:
    """Collect the grounding evidence a recipe requires. Returns (evidence, missing)."""
    root = Path(root)
    evidence: dict[str, Any] = {}
    missing: list[str] = []
    for kind in recipe.required_evidence:
        if kind == "established_baseline":
            registry = baseline_registry.BaselineRegistry(root / "autonomous_agent" / "state")
            record = registry.active()
            problems = (baseline_registry.validate_established_record(record)
                        if record is not None else ["No established baseline record exists."])
            if problems:
                missing.append(f"established_baseline: {'; '.join(problems)}")
            else:
                evidence["established_baseline"] = {
                    "baseline_id": record.get("baseline_id"),
                    "pipeline_fingerprint": record.get("pipeline_fingerprint"),
                    "registry": "baseline_registry.json",
                }
        elif kind == "prior_findings_in_direction":
            memory = read_json(root / "autonomous_agent" / "state" / "research_memory.json", {})
            discoveries = [item for item in memory.get("discoveries", [])
                           if isinstance(item, dict) and item.get("direction") == recipe.direction]
            if not discoveries:
                missing.append(
                    f"prior_findings_in_direction: no recorded findings in direction "
                    f"{recipe.direction!r}; the recipe refuses to speculate without evidence.")
            else:
                evidence["prior_findings_in_direction"] = [
                    {"experiment_id": item.get("experiment_id"),
                     "status": item.get("status"),
                     "created_at": item.get("created_at")}
                    for item in discoveries[-3:]
                ]
        else:
            missing.append(f"unknown required evidence kind {kind!r} (recipe is malformed).")
    return evidence, missing


# ---------------------------------------------------------------------------
# Recipe validation (malformed recipes are refused, never guessed at)
# ---------------------------------------------------------------------------

def validate_recipe(recipe: Recipe) -> list[str]:
    """Return why a recipe is unusable (empty list = valid)."""
    problems: list[str] = []
    if not recipe.recipe_id or not all(ch.isalnum() or ch in "._-" for ch in recipe.recipe_id):
        problems.append(f"Invalid recipe_id {recipe.recipe_id!r}.")
    if not recipe.version:
        problems.append("Recipe version must be declared.")
    if not recipe.purpose or not recipe.purpose.strip():
        problems.append("Recipe purpose must state what the experiment tests.")
    if not recipe.direction:
        problems.append("Recipe must declare its research direction.")
    if not recipe.target_files:
        problems.append("Recipe must declare permitted target files.")
    for target in recipe.target_files:
        try:
            normalized = _require_allowed_path(target)
        except Exception as error:  # noqa: BLE001 - report, do not raise
            problems.append(f"Target file {target!r} is not on the experiment allowlist: {error}")
            continue
        if not normalized.startswith(EXPERIMENT_DIR):
            problems.append(f"Target file {target!r} escapes {EXPERIMENT_DIR}.")
    if not recipe.parameter_grid:
        problems.append("Recipe must declare a non-empty parameter grid.")
    for name, values in recipe.parameter_grid.items():
        if not isinstance(values, tuple) or not values:
            problems.append(f"Parameter {name!r} must declare a non-empty tuple of values.")
        if name == "estimator" and not set(values) <= {"LogisticRegression", "LightGBM"}:
            problems.append(f"Parameter {name!r} has unreviewed values {values!r}.")
        if name == "arm_pair":
            reviewed_pairs = {("A", "B"), ("B", "C"), ("C", "D")}
            for value in values:
                if not isinstance(value, str) or "->" not in value:
                    problems.append(f"arm_pair value {value!r} must look like 'A->B'.")
                else:
                    left, right = value.split("->", 1)
                    if (left, right) not in reviewed_pairs and left != right:
                        problems.append(
                            f"arm_pair {value!r} is not a reviewed nested pair or same-arm pair.")
        if name == "n_boot":
            for value in values:
                if isinstance(value, bool) or not isinstance(value, int) or not 100 <= value <= 2000:
                    problems.append(f"n_boot value {value!r} is outside [100, 2000].")
        if name == "calibration_bins":
            for value in values:
                if isinstance(value, bool) or not isinstance(value, int) or not 3 <= value <= 20:
                    problems.append(f"calibration_bins value {value!r} is outside [3, 20].")
    if not recipe.required_evidence:
        problems.append("Recipe must declare required grounding evidence.")
    if not recipe.evaluation_criteria:
        problems.append("Recipe must predeclare evaluation criteria.")
    if "primary_metric_min_delta" not in recipe.evaluation_criteria:
        problems.append("Recipe evaluation criteria must include primary_metric_min_delta.")
    if not recipe.rejection_conditions:
        problems.append("Recipe must document its rejection conditions.")
    if isinstance(recipe.max_attempts, bool) or not isinstance(recipe.max_attempts, int) \
            or recipe.max_attempts < 1:
        problems.append("max_attempts must be a positive integer.")
    return problems


def validated_library(library: Sequence[Recipe] | None = None) -> tuple[list[Recipe], dict[str, list[str]]]:
    """Return (valid recipes, {recipe_id: problems}); malformed recipes never pass."""
    valid: list[Recipe] = []
    problems: dict[str, list[str]] = {}
    for recipe in (library if library is not None else RECIPE_LIBRARY):
        recipe_problems = validate_recipe(recipe)
        if recipe_problems:
            problems[recipe.recipe_id or "<unnamed>"] = recipe_problems
        else:
            valid.append(recipe)
    return valid, problems


