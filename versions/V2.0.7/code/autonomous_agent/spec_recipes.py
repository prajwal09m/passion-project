"""Deterministic, recipe-based autonomous ExperimentSpec generation.

This module replaces the missing ``spec_provider`` with a *closed, reviewed
recipe library* and a *deterministic* spec provider. Important scope note:

**There is no LLM in this system.** Generation is deterministic template
rendering over the reviewed recipes below -- the same hypothesis, evidence and
state always select the same recipe and the same parameters (only the recorded
``generated_at`` timestamp differs). No model provider is configured or
consulted anywhere in this path, and none may be added without a review that
replaces this module's closed library.

Safety contract (all of this is in addition to -- never instead of -- the
adapter's downstream protections, which continue to run unmodified):

* The library is **closed**. A recipe can only ever produce files inside
  ``autonomous_agent/experiments/**`` and only from its own reviewed template;
  the provider never invents code mutations and never expands the allowlist.
* Every generated spec carries **provenance**: generator type, recipe id and
  version, hypothesis id, the grounding evidence records, the selected
  parameters, and a generation timestamp.
* Proposals that are unsupported (no recipe covers the hypothesis), missing
  required evidence, out of budget, or duplicates of already-attempted specs
  are **refused** -- a refusal raises :class:`SpecGenerationRefused` and the
  supervisor records a normal REJECTED cycle. Nothing is silently weakened.
* ``allow_autonomous_specs`` defaults to False. When disabled this provider
  refuses every request, and :func:`build_default_provider` returns ``None`` so
  the runner behaves exactly as before (candidate specs prohibited).

Deterministic parameter selection: for each recipe the parameter grid is
enumerated in sorted order and the N-th generation attempt for that recipe
selects grid index ``N % len(grid)`` where N is counted from the recipe's own
attempt ledger (``autonomous_agent/state/spec_attempts.json``). The ledger is
append-only and crash-safe (attempt rows are written before the spec is
returned, so a crash can only lose a never-used spec, never double-run one).
"""
