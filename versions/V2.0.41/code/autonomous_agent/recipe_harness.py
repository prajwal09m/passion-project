def evaluate_horizon_rungs(rung_measurements: list[dict], *,
                           floors: Mapping[str, Any]) -> dict:
    """Target-horizon robustness: every horizon rung must independently hold.

    Each rung must already carry rebuilt labels and a re-verified maturity
    purge; this function refuses a rung that does not declare them, so a
    caller cannot reuse pooled labels across horizons.
    """
    from autonomous_agent import three_valued as tv
    ladder = tv.ladder_for("target_horizon_robustness")
    seen = [m["rung"] for m in rung_measurements]
    if sorted(seen) != sorted(ladder["rungs"]):
        raise ValueError(
            f"horizon rungs {sorted(seen)} do not match the frozen ladder "
            f"{sorted(ladder['rungs'])}")
    for m in rung_measurements:
        if m.get("labels_rebuilt") is not True:
            raise ValueError(
                f"horizon rung {m['rung']}: labels must be rebuilt per rung; "
                f"reusing pooled labels is refused")
        if m.get("maturity_purge_reverified") is not True:
            raise ValueError(
                f"horizon rung {m['rung']}: the maturity purge must be "
                f"re-verified after the label rebuild")
    conditions = [
        tv.evaluate_condition(
            name=f"horizon_{m['rung']}", point=float(m["point"]),
            ci_lower=float(m["ci_lower"]), margin=_margin(),
            n_rows=m.get("n_rows"), n_events=m.get("n_events"),
            min_rows=int(floors["min_rows"]),
            min_events=int(floors["min_events"]))
        for m in rung_measurements]
    return tv.combine_iut("target_horizon_robustness", conditions).to_dict()


def evaluate_complexity_reduction(measurement: Mapping[str, Any], *,
                                  floors: Mapping[str, Any]) -> dict:
    """Complexity reduction: does the simpler model hold within-margin?

    A single primary rung. The result is always stamped as a RELATED
    REANALYSIS of ``model_class_comparison`` so no reader can mistake it for
    independent confirmation (count-once rule).
    """
    from autonomous_agent import three_valued as tv
    ladder = tv.ladder_for("complexity_reduction_check")
    if measurement.get("rung") != ladder["rungs"][0]:
        raise ValueError(
            f"complexity reduction has one primary rung "
            f"{ladder['rungs'][0]!r}; got {measurement.get('rung')!r}")
    condition = tv.evaluate_condition(
        name="reduction_primary", point=float(measurement["point"]),
        ci_lower=float(measurement["ci_lower"]), margin=_margin(),
        n_rows=measurement.get("n_rows"),
        n_events=measurement.get("n_events"),
        min_rows=int(floors["min_rows"]),
        min_events=int(floors["min_events"]))
    result = tv.combine_iut("complexity_reduction_check", (condition,)).to_dict()
    result["related_primitive"] = ladder["related_primitive"]
    result["independent_confirmation"] = False
    result["disclosure"] = (
        "related reanalysis of model_class_comparison; never independent "
        "confirmation, and the count-once rule applies to any evidence tally")
    return result


def evaluate_point_in_time_audit(checks: Mapping[str, str], *,
                                 manifest_errors: Any | None = None) -> dict:
    """Point-in-time audit: tri-state, fail-closed, R-4 aware.

    * UNVERIFIABLE never returns PASS (a missing manifest entry blocks PASS).
    * A disclosed Tier-2 defect is an audit FAIL, never contamination (R-4).
    * CONFIRMED_CONTAMINATION halts the campaign.
    Structural results never upgrade a value verdict.

    ``manifest_errors`` is the caller's precomputed census-manifest
    validation result (a non-empty sequence blocks a CLEAN pass — R-1).
    The census machinery itself stays imported only by its own tests
    (inertness rule); the harness consumes its verdict, never the module.
    """
    from autonomous_agent import three_valued as tv
    ladder = tv.ladder_for("point_in_time_data_audit")
    unknown = sorted(set(checks) - set(ladder["rungs"]))
    if unknown:
        raise ValueError(
            f"audit checks {unknown} are not in the frozen audit suite "
            f"{ladder['rungs']}")
    missing = sorted(set(ladder["rungs"]) - set(checks))
    if missing:
        raise ValueError(f"audit checks {missing} were not run; the audit is "
                         f"all-or-nothing")
    outcome = tv.audit_tri_state(dict(checks))
    # R-1: an unfrozen tolerance or a missing entry blocks a PASS.
    manifest_blocked = bool(list(manifest_errors or ()))
    if outcome == "CLEAN" and manifest_blocked:
        outcome = "UNVERIFIABLE"
    return {
        "primitive_id": "point_in_time_data_audit",
        "status": outcome,
        "checks": dict(checks),
        "manifest_blocked_pass": manifest_blocked,
        "formal_refutation": False,
        "note": ("tri-state audit; UNVERIFIABLE never returns PASS; a "
                 "disclosed Tier-2 defect is an audit FAIL, never "
                 "contamination (owner ruling R-4)"),
    }


def _margin():
    from autonomous_agent import three_valued as tv
    return tv.Margin(value=0.0, ci_lower_min=tv.PROVISIONAL_MARGIN)


