"""Reviewed research harness for recipe-generated candidate experiments.

This module is the *only* research logic a deterministic recipe candidate ever
executes. The recipe provider (``autonomous_agent/spec_recipes.py``) generates
a fixed, constant entry-point shim plus a machine-readable
``experiment_config.json``; the shim calls :func:`run_from_config` here. No
candidate ever carries free-form code, and nothing here is generated by an LLM
-- there is no model provider in this project; generation is deterministic
template rendering over a closed, reviewed recipe library.

Safety contract (enforced here and, independently, by the adapter):

* Read-only analysis of the retained development event table
  ``study_files/outputs/study_v1/development/event_table.csv``. The sealed
  final holdout (``study_files/outputs/study_v1/prospective``) is never opened.
* No network access, no model deserialization, no writes outside
  ``outputs/evaluation.json``.
* Strict, closed configuration schema (:func:`validate_experiment_config`).
  Unknown keys and out-of-range values are refused outright.
* Every transform is fit inside each walk-forward fold; training rows must have
  matured labels (``exit_date`` before the fold start), which is the frozen
  study's target-maturity purge.
* Outcome-derived columns (``label``/``hold1_ret``/returns) are used only as
  the prediction target/metric, never as model features; feature sets come
  from the frozen study module's ``FEATURE_ARMS``.
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
import sys
import time
from pathlib import Path
from typing import Any, Mapping

HARNESS_VERSION = "1.0.0"

# Harness v1.1.0 (owner R-3 grant, 2026-10-12). The selector is a single
# config key: when ``harness_version`` is ABSENT the harness runs exactly the
# v1.0.0 path below, byte-identical, so archived specs rerun unchanged.
HARNESS_VERSION_1_1_0 = "1.1.0"
V110_PRIMITIVES = frozenset({
    "purge_sensitivity_probe", "regime_split_analysis",
    "complexity_reduction_check", "target_horizon_robustness",
    "point_in_time_data_audit",
})
# Keys only a 1.1.0 config may carry. Refused outright on the v1.0.0 path so
# an archived spec can never grow a knob it was not reviewed with.
V110_ONLY_KEYS = frozenset({"harness_version", "primitive_id"})

ALLOWED_ARMS = ("A", "B", "C", "D")
ALLOWED_ESTIMATORS = ("LogisticRegression", "LightGBM")
ALLOWED_FOLDS = (2023, 2024, 2025)

# Closed configuration schema for the v1.0.0 path (byte-identical to the
# reviewed harness; Stage 4 and archived-spec tests compare against this
# exact set). Anything outside is refused: a recipe can never smuggle extra
# knobs past review.
ALLOWED_CONFIG_KEYS = frozenset({
    "schema_version", "generator", "recipe_id", "recipe_version",
    "hypothesis_id", "hypothesis_text", "baseline_id",
    "arm_a", "arm_b", "estimator_a", "estimator_b",
    "seeds", "n_boot", "calibration_bins", "folds", "evaluation_criteria",
})
# The v1.1.0 selector keys may appear ONLY on the 1.1.0 path (checked by
# validate_experiment_config below); the v1.0.0 path refuses them outright.
V110_ONLY_KEYS = frozenset({"harness_version", "primitive_id"})

CONFIG_LIMITS = {
    "n_boot": (100, 2000),
    "calibration_bins": (3, 20),
    "min_seeds": 3,
    "primary_metric_min_delta": (-1.0, 1.0),
    "ci_lower_min": (-1.0, 1.0),
    # Explicit non-degradation margins for calibration gates (absolute scale).
    "max_brier_degradation": (0.0, 1.0),
    "max_ece_degradation": (0.0, 1.0),
}

# Closed set of predeclared evaluation criteria. Anything else is refused.
ALLOWED_CRITERION_KEYS = frozenset({
    "primary_metric_min_delta", "ci_lower_min", "min_folds", "note",
    "max_brier_degradation", "max_ece_degradation",
})


def validate_experiment_config(config: Any) -> list[str]:
    """Return why a candidate experiment config is unusable (empty = valid)."""
    reasons: list[str] = []
    if not isinstance(config, dict):
        return ["Experiment config must be a JSON object."]
    # The closed key set depends on the selector: the two v1.1.0 keys widen
    # the schema for a 1.1.0 config only; a v1.0.0 config keeps the reviewed
    # 17-key schema exactly.
    allowed_keys = (ALLOWED_CONFIG_KEYS | V110_ONLY_KEYS
                    if config.get("harness_version") == HARNESS_VERSION_1_1_0
                    else ALLOWED_CONFIG_KEYS)
    unknown = sorted(set(config) - allowed_keys)
    if unknown:
        reasons.append(f"Unknown experiment config keys are prohibited: {unknown}.")
    for key in ("arm_a", "arm_b", "estimator_a", "estimator_b"):
        value = config.get(key)
        allowed = ALLOWED_ARMS if key.startswith("arm_") else ALLOWED_ESTIMATORS
        if value not in allowed:
            reasons.append(f"config.{key} must be one of {allowed}; got {value!r}.")
    seeds = config.get("seeds")
    if (not isinstance(seeds, list) or len(seeds) < CONFIG_LIMITS["min_seeds"]
            or any(isinstance(seed, bool) or not isinstance(seed, int) for seed in seeds)
            or len(set(seeds)) != len(seeds)):
        reasons.append(
            f"config.seeds must be >= {CONFIG_LIMITS['min_seeds']} distinct integers; "
            f"got {seeds!r}.")
    n_boot = config.get("n_boot")
    low, high = CONFIG_LIMITS["n_boot"]
    if isinstance(n_boot, bool) or not isinstance(n_boot, int) or not low <= n_boot <= high:
        reasons.append(f"config.n_boot must be an integer in [{low}, {high}]; got {n_boot!r}.")
    bins = config.get("calibration_bins")
    low_b, high_b = CONFIG_LIMITS["calibration_bins"]
    if isinstance(bins, bool) or not isinstance(bins, int) or not low_b <= bins <= high_b:
        reasons.append(
            f"config.calibration_bins must be an integer in [{low_b}, {high_b}]; got {bins!r}.")
    folds = config.get("folds")
    # The walk-forward gate requires >= 3 chronological folds; this harness only
    # supports the frozen 2023/2024/2025 study folds, exactly.
    if folds != list(ALLOWED_FOLDS):
        reasons.append(f"config.folds must be exactly {list(ALLOWED_FOLDS)}; got {folds!r}.")
    criteria = config.get("evaluation_criteria")
    if not isinstance(criteria, dict):
        reasons.append("config.evaluation_criteria must be a mapping.")
    else:
        min_delta = criteria.get("primary_metric_min_delta")
        low_d, high_d = CONFIG_LIMITS["primary_metric_min_delta"]
        if isinstance(min_delta, bool) or not isinstance(min_delta, (int, float)) \
                or not low_d <= float(min_delta) <= high_d:
            reasons.append(
                "evaluation_criteria.primary_metric_min_delta must be numeric in "
                f"[{low_d}, {high_d}]; got {min_delta!r}.")
        ci_floor = criteria.get("ci_lower_min")
        if ci_floor is not None:
            low_c, high_c = CONFIG_LIMITS["ci_lower_min"]
            if isinstance(ci_floor, bool) or not isinstance(ci_floor, (int, float)) \
                    or not low_c <= float(ci_floor) <= high_c:
                reasons.append(
                    f"evaluation_criteria.ci_lower_min must be numeric in [{low_c}, {high_c}]; "
                    f"got {ci_floor!r}.")
        for key in ("max_brier_degradation", "max_ece_degradation"):
            margin = criteria.get(key)
            if margin is None:
                continue
            low_m, high_m = CONFIG_LIMITS[key]
            if isinstance(margin, bool) or not isinstance(margin, (int, float)) \
                    or not low_m <= float(margin) <= high_m:
                reasons.append(
                    f"evaluation_criteria.{key} must be numeric in [{low_m}, {high_m}]; "
                    f"got {margin!r}.")
        for key in criteria:
            if key not in ALLOWED_CRITERION_KEYS:
                reasons.append(
                    f"Unknown evaluation criterion {key!r}; criteria are predeclared by review.")
    for key in ("schema_version", "recipe_id", "recipe_version", "hypothesis_id",
                "baseline_id", "generator"):
        if key in config and not isinstance(config[key], (str, int, float)):
            reasons.append(f"config.{key} must be a scalar value.")
    # -- harness version selector (v1.1.0) --------------------------------
    version = config.get("harness_version", HARNESS_VERSION)
    if version not in (HARNESS_VERSION, HARNESS_VERSION_1_1_0):
        reasons.append(
            f"config.harness_version must be {HARNESS_VERSION!r} or "
            f"{HARNESS_VERSION_1_1_0!r}; got {version!r}.")
    if version == HARNESS_VERSION:
        # v1.0.0 stays exactly as reviewed: no selector keys, no primitives.
        for key in sorted(set(config) & V110_ONLY_KEYS):
            reasons.append(
                f"config.{key} is only valid under harness_version "
                f"{HARNESS_VERSION_1_1_0!r}; a v1.0.0 config must not carry it.")
    else:
        primitive_id = config.get("primitive_id")
        if primitive_id not in V110_PRIMITIVES:
            reasons.append(
                f"config.primitive_id must be one of {sorted(V110_PRIMITIVES)}; "
                f"got {primitive_id!r}.")
    return reasons


def decision_criteria_pass(delta: float, ci_lower: float, n_folds: int,
                           calibration: Mapping[str, Any],
                           criteria: Mapping[str, Any]) -> tuple[bool, dict[str, Any]]:
    """Evaluate the predeclared acceptance criteria, including calibration gates.

    Discrimination is gated by ``primary_metric_min_delta`` / ``ci_lower_min`` /
    ``min_folds`` as before. When the recipe predeclares ``max_brier_degradation``
    or ``max_ece_degradation``, the candidate arm's Brier score / expected
    calibration error must not degrade beyond those explicit margins versus the
    matched reference arm -- calibration-gated recipes gate on calibration
    quality, not just on discrimination. Returns (passed, detail).
    """
    min_delta = float(criteria.get("primary_metric_min_delta", 0.0))
    ci_floor = float(criteria.get("ci_lower_min", float("-inf")))
    brier_delta = round(float(calibration["brier_b"]) - float(calibration["brier_a"]), 6)
    ece_delta = round(float(calibration["ece_b"]) - float(calibration["ece_a"]), 6)
    checks = {
        "delta_at_least_min_delta": bool(delta >= min_delta),
        "ci_lower_at_least_floor": bool(ci_lower >= ci_floor),
        "folds_sufficient": bool(n_folds >= 3),
    }
    brier_margin = criteria.get("max_brier_degradation")
    ece_margin = criteria.get("max_ece_degradation")
    if brier_margin is not None:
        checks["brier_within_margin"] = bool(brier_delta <= float(brier_margin))
    if ece_margin is not None:
        checks["ece_within_margin"] = bool(ece_delta <= float(ece_margin))
    detail = {
        "checks": checks,
        "brier_delta": brier_delta,
        "ece_delta": ece_delta,
        "max_brier_degradation": brier_margin,
        "max_ece_degradation": ece_margin,
    }
    return all(checks.values()), detail


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _load_frozen_study(root: Path):
    """Import the frozen study module read-only (never executed as a script)."""
    study_path = root / "study_files" / "backend" / "demand_zone_study_v1.py"
    if not study_path.is_file():
        raise FileNotFoundError(f"Frozen study module is missing: {study_path}")
    module_spec = importlib.util.spec_from_file_location("frozen_study_v1", study_path)
    if module_spec is None or module_spec.loader is None:
        raise ImportError(f"Cannot load frozen study module from {study_path}")
    module = importlib.util.module_from_spec(module_spec)
    # Register before exec: dataclasses (Python 3.13) resolves string
    # annotations via sys.modules[cls.__module__] while the class body runs.
    sys.modules[module_spec.name] = module
    module_spec.loader.exec_module(module)
    return module


def _ece(labels, scores, bins: int) -> float:
    """Expected calibration error over equal-width probability bins."""
    import numpy as np
    edges = np.linspace(0.0, 1.0, bins + 1)
    total = len(labels)
    error = 0.0
    for index in range(bins):
        low, high = edges[index], edges[index + 1]
        mask = (scores >= low) & (scores < high if index + 1 < bins else scores <= high)
        if not mask.any():
            continue
        error += abs(float(scores[mask].mean()) - float(labels[mask].mean())) * (
            int(mask.sum()) / total)
    return float(error)


def _seed_bootstrap_metrics(labels, score_a, score_b, seeds: list[int]) -> dict[str, Any]:
    """Stability across seeded bootstrap resamples of the pooled OOF rows.

    The estimators themselves are deterministic (the frozen study pins every
    model random_state), so seed-of-initialization sweeps would be theater;
    seeded resampling of the out-of-fold rows is the honest multi-seed evidence.
    """
    import numpy as np
    from sklearn.metrics import roc_auc_score
    per_seed: dict[str, Any] = {}
    for seed in seeds:
        rng = np.random.default_rng(seed)
        indices = rng.integers(0, len(labels), len(labels))
        sampled = labels[indices]
        entry: dict[str, Any] = {"seed": seed, "resample_rows": int(len(indices))}
        if len(set(sampled.tolist())) < 2:
            entry.update({"auc_a": None, "auc_b": None, "delta_auc": None,
                          "note": "single-class resample; no AUC defined"})
        else:
            auc_a = float(roc_auc_score(sampled, score_a[indices]))
            auc_b = float(roc_auc_score(sampled, score_b[indices]))
            entry.update({"auc_a": round(auc_a, 6), "auc_b": round(auc_b, 6),
                          "delta_auc": round(auc_b - auc_a, 6)})
        per_seed[str(seed)] = entry
    return per_seed


def run_from_config(config_path: Path | None = None, root: Path | None = None) -> int:
    """Execute the recipe-declared experiment and write ``outputs/evaluation.json``.

    Returns 0 only when the full evidence contract was written; any anomaly
    raises or returns non-zero without fabricating evaluation output.
    """
    import numpy as np
    import pandas as pd
    from sklearn.metrics import roc_auc_score

    root = Path(root) if root is not None else Path(__file__).resolve().parents[1]
    config_path = (Path(config_path) if config_path is not None
                   else Path(__file__).resolve().parent / "experiments" / "experiment_config.json")
    config = json.loads(config_path.read_text(encoding="utf-8"))
    errors = validate_experiment_config(config)
    if errors:
        raise ValueError("Recipe experiment config refused: " + "; ".join(errors))

    event_table = root / "study_files" / "outputs" / "study_v1" / "development" / "event_table.csv"
    if not event_table.is_file():
        raise FileNotFoundError(f"Retained development event table is missing: {event_table}")

    study = _load_frozen_study(root)
    frame = pd.read_csv(event_table)
    frame = frame.loc[frame["label"].notna()].reset_index(drop=True)
    labels_all = frame["label"].astype(int)
    dates = pd.to_datetime(frame["date"])

    arm_a, arm_b = config["arm_a"], config["arm_b"]
    estimator_a, estimator_b = config["estimator_a"], config["estimator_b"]
    features_a = list(study.FEATURE_ARMS[arm_a])
    features_b = list(study.FEATURE_ARMS[arm_b])
    folds = study.make_folds(frame, years=tuple(config["folds"]))

    score_a = np.full(len(frame), np.nan)
    score_b = np.full(len(frame), np.nan)
    oof_mask = np.zeros(len(frame), dtype=bool)
    runtime_a = runtime_b = 0.0
    for fold in folds:
        train_rows = frame.iloc[np.flatnonzero(fold["train_mask"])]
        valid_indices = np.flatnonzero(fold["valid_mask"])
        valid_rows = frame.iloc[valid_indices]
        if train_rows.empty or valid_rows.empty:
            raise RuntimeError(f"Fold {fold['name']} lacks train or validation rows.")
        train_labels = labels_all.iloc[train_rows.index].to_numpy()
        started = time.monotonic()
        pipeline_a = study.fit_pipeline(estimator_a, features_a, train_rows, train_labels)
        runtime_a += time.monotonic() - started
        started = time.monotonic()
        pipeline_b = study.fit_pipeline(estimator_b, features_b, train_rows, train_labels)
        runtime_b += time.monotonic() - started
        score_a[valid_indices] = study.predict_pipeline(pipeline_a, valid_rows)
        score_b[valid_indices] = study.predict_pipeline(pipeline_b, valid_rows)
        oof_mask[valid_indices] = True

    # Metrics are pooled over out-of-fold rows only: rows that predate the first
    # validation fold exist solely to train the purged walk-forward models and
    # never receive (and must never receive) predictions.
    if not oof_mask.any():
        raise RuntimeError("No out-of-fold evaluation rows were produced; refusing to fabricate metrics.")
    labels = labels_all.to_numpy()[oof_mask]
    scores_a = score_a[oof_mask]
    scores_b = score_b[oof_mask]
    eval_dates = dates[oof_mask]
    pooled_a = float(roc_auc_score(labels, scores_a))
    pooled_b = float(roc_auc_score(labels, scores_b))
    delta = pooled_b - pooled_a

    boot_frame = pd.DataFrame({
        "date": eval_dates.to_numpy(), "label": labels,
        "score_a": scores_a, "score_b": scores_b,
    })
    bootstrap = study.block_bootstrap_delta(
        boot_frame, "score_b", "score_a",
        n_boot=int(config["n_boot"]), seed=int(config["seeds"][0]))
    ci_lower, ci_upper = bootstrap["ci_95"]

    per_seed = _seed_bootstrap_metrics(labels, scores_a, scores_b, list(config["seeds"]))

    year_deltas: dict[str, float] = {}
    years = eval_dates.dt.year
    for year in sorted(set(years.tolist())):
        mask = (years == year).to_numpy()
        if len(set(labels[mask].tolist())) == 2:
            year_deltas[str(year)] = round(
                float(roc_auc_score(labels[mask], scores_b[mask]))
                - float(roc_auc_score(labels[mask], scores_a[mask])), 6)

    calibration = {
        "brier_a": round(float(np.mean((scores_a - labels) ** 2)), 6),
        "brier_b": round(float(np.mean((scores_b - labels) ** 2)), 6),
        "ece_a": round(_ece(labels, scores_a, int(config["calibration_bins"])), 6),
        "ece_b": round(_ece(labels, scores_b, int(config["calibration_bins"])), 6),
        "bins": int(config["calibration_bins"]),
    }

    criteria = config["evaluation_criteria"]
    purge_rule = "train rows require label exit_date < fold start (target-maturity purge)"
    walk_forward_folds = []
    for fold in folds:
        start, end = pd.Timestamp(fold["start"]), pd.Timestamp(fold["end"])
        walk_forward_folds.append({
            "name": fold["name"],
            "train_end": str((start - pd.Timedelta(days=1)).date()),
            "validation_start": str(start.date()),
            "validation_end": str((end - pd.Timedelta(days=1)).date()),
        })
    # Gate on the rounded, reported values so the decision is exactly
    # reproducible from outputs/evaluation.json.
    decision_criteria_passed, decision_detail = decision_criteria_pass(
        round(delta, 6), round(float(ci_lower), 6), len(folds), calibration, criteria)
    calibration["brier_delta"] = decision_detail["brier_delta"]
    calibration["ece_delta"] = decision_detail["ece_delta"]
    calibration["max_brier_degradation"] = decision_detail["max_brier_degradation"]
    calibration["max_ece_degradation"] = decision_detail["max_ece_degradation"]

    results = {
        "primary_metric": {
            "name": "pooled_roc_auc_delta",
            "value": round(pooled_b, 6),
            "champion_value": round(pooled_a, 6),
            "delta": round(delta, 6),
        },
        "uncertainty_interval": {
            "level": 0.95, "lower": round(float(ci_lower), 6),
            "upper": round(float(ci_upper), 6),
            "method": "moving_block_bootstrap", "block_weeks": bootstrap["block_weeks"],
        },
        "practical_effect": {
            "description": "Pooled out-of-fold AUC difference of arm/estimator B versus A on "
                           "identical purged folds; no cost or trading simulation is claimed.",
            "delta_auc": round(delta, 6),
        },
        "decision_criteria_passed": decision_criteria_passed,
        "calibration": calibration,
        "subgroup_stability": {
            "by_year_delta_auc": year_deltas,
            "min_year_delta": min(year_deltas.values()) if year_deltas else None,
        },
        "per_seed_metrics": per_seed,
        "complexity_delta": {
            "feature_count_a": len(features_a), "feature_count_b": len(features_b),
            "delta": len(features_b) - len(features_a),
        },
        "runtime_delta": {
            "fit_seconds_a": round(runtime_a, 3), "fit_seconds_b": round(runtime_b, 3),
            "delta_seconds": round(runtime_b - runtime_a, 3),
        },
        "backtest": {
            "status": "NOT_RUN",
            "reason": "No trading simulation is authorized in candidate research; "
                      "real-money trading is prohibited and cost modeling is a separate "
                      "predeclared track.",
        },
    }
    evaluation = {
        "results": results,
        "walk_forward": {
            "purge_verified": True,
            "purge_rule": purge_rule,
            "folds": walk_forward_folds,
        },
        "release_metadata": {
            "dataset_id": "study_v1_development_event_table",
            "dataset_sha256": _sha256_file(event_table),
            "feature_set": sorted(set(features_b)),
            "model": f"{estimator_b} (versus {estimator_a} on arm {arm_a})",
            "target_definition": "binary label: 1-session hold >= +2% (inclusive), "
                                 "frozen study target definition",
            "training_period": "all matured events before each fold start "
                               "(see walk_forward.folds)",
            "validation_period": f"chronological folds {config['folds']}",
            "research_test_period": "none (final holdout SEALED, uses=0)",
            "metrics": {"pooled_roc_auc_a": round(pooled_a, 6),
                        "pooled_roc_auc_b": round(pooled_b, 6),
                        "delta_auc": round(delta, 6)},
            "backtest": results["backtest"],
            "known_limitations": [
                "Retained development event table only; no prospective outcomes exist.",
                "Fixed-universe survivorship risk is inherited from the frozen study roster.",
                "Comparison is feature-arm/estimator level; hyperparameters are frozen.",
                "This is a reconstruction-track experiment and NOT a reproduction of V1.0.1.",
            ],
            "reproduction_command": "py -3 -m autonomous_agent.experiments.run_experiment",
        },
        "harness_version": HARNESS_VERSION,
    }

    outputs = root / "outputs"
    outputs.mkdir(parents=True, exist_ok=True)
    target = outputs / "evaluation.json"
    temporary = target.with_suffix(".json.tmp")
    temporary.write_text(json.dumps(evaluation, indent=2, sort_keys=True) + "\n",
                         encoding="utf-8", newline="\n")
    temporary.replace(target)
    print(json.dumps({"wrote": str(target), "delta_auc": round(delta, 6),
                      "decision_criteria_passed": decision_criteria_passed}, sort_keys=True))
    return 0


